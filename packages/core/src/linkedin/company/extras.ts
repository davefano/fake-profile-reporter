// Company details only a signed-in viewer gets: page ownership, whether the
// company pays LinkedIn, and a sample of its employees' account ages. From the
// employee search only counts are kept, never who the people are.

import { endpoints } from '../endpoints';
import { memberIdFromProfileId, profileIdFromUrn } from '../ids';
import { estimateJoinedAt } from '../join-estimate';
import { errorText } from '../errors';
import { sessionFrom, type ReaderOptions } from '../session';

export interface EmployeeSample {
  /** Total people LinkedIn lists as current employees. */
  total: number | null;
  /** Profiles in the sample (one search page). */
  sampled: number;
  /** "LinkedIn Member" results whose details are hidden from the viewer. */
  hidden: number;
  /** Visible profiles whose account is under a year old (estimated from member ID). */
  newAccounts: number;
  /** Visible profiles older than five years. */
  oldAccounts: number;
}

export interface CompanyExtras {
  /** LinkedIn created the page itself; nobody manages it. */
  autoGenerated: boolean | null;
  /** Nobody has claimed the page. */
  claimable: boolean | null;
  /** The company pays LinkedIn for something (ads, recruiting, …). */
  paid: boolean | null;
  staffing: boolean | null;
  phone: string | null;
  locations: number | null;
  employees: EmployeeSample | null;
  /** Parts that failed, e.g. { employees: "HTTP 400" } when the search query rotated. */
  errors: Record<string, string>;
}

export function parseCompanyRecord(json: unknown, slug: string): Omit<CompanyExtras, 'employees' | 'errors'> & { companyId: number | null } {
  const co = ((json as any)?.included ?? []).find((e: any) => e?.$type === 'com.linkedin.voyager.organization.Company' && e.universalName === slug);
  const bool = (v: unknown) => (typeof v === 'boolean' ? v : null);
  return {
    companyId: Number(/:(\d+)$/.exec(co?.entityUrn ?? '')?.[1]) || null,
    autoGenerated: bool(co?.autoGenerated),
    claimable: bool(co?.claimable),
    paid: bool(co?.paidCompany),
    staffing: bool(co?.staffingCompany),
    phone: typeof co?.phone?.number === 'string' ? co.phone.number.trim() : null,
    locations: Array.isArray(co?.confirmedLocations) ? co.confirmedLocations.length : null,
  };
}

const YEAR = 365.25 * 86_400_000;

export function parsePeopleSearch(json: unknown, now = Date.now()): EmployeeSample {
  const results = ((json as any)?.included ?? []).filter((e: any) => /EntityResultViewModel$/.test(e?.$type ?? ''));
  let hidden = 0;
  let newAccounts = 0;
  let oldAccounts = 0;
  for (const r of results) {
    const member = /urn:li:member:(\d+)/.exec(r.trackingUrn ?? '')?.[1];
    const profileId = profileIdFromUrn(/urn:li:fsd_profile:[\w-]+/.exec(r.entityUrn ?? '')?.[0]);
    const memberId = member ? Number(member) : memberIdFromProfileId(profileId);
    if (!memberId) {
      hidden++;
      continue;
    }
    const joined = estimateJoinedAt(memberId, now);
    if (joined == null) continue;
    if (now - joined < YEAR) newAccounts++;
    else if (now - joined > 5 * YEAR) oldAccounts++;
  }
  return { total: findTotal((json as any)?.data), sampled: results.length, hidden, newAccounts, oldAccounts };
}

function findTotal(node: any, depth = 0): number | null {
  if (!node || typeof node !== 'object' || depth > 8) return null;
  if (node.paging && typeof node.paging.total === 'number') return node.paging.total;
  for (const v of Object.values(node)) {
    const t = findTotal(v, depth + 1);
    if (t != null) return t;
  }
  return null;
}

export async function fetchCompanyExtras(slug: string, opts: ReaderOptions & { now?: number } = {}): Promise<CompanyExtras> {
  const s = sessionFrom(opts);
  const { companyId, ...record } = parseCompanyRecord(await s.voyager(endpoints.companyRecord(slug)), slug);
  const errors: Record<string, string> = {};
  let employees: EmployeeSample | null = null;
  if (companyId) {
    try {
      employees = parsePeopleSearch(await s.voyager(endpoints.companyPeople(companyId)), opts.now);
    } catch (e) {
      errors.employees = errorText(e); // the search query id rotates; the rest still counts
    }
  }
  return { ...record, employees, errors };
}
