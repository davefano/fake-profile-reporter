// Suspicion score for a company page. Fake employers usually need a page to
// post jobs from; the tells are claims (size, history) with nothing behind
// them, or a page that borrows a real brand's name.

import type { CompanyFacts } from '../linkedin/company/facts';
import { siteDomain } from '../linkedin/url';
import { finishScore, signalAdder, type Score, type Signal } from './signals';

// Hosts that anyone can get a page on in minutes; not a company's own domain.
export const FREE_HOSTS = /(^|\.)(sites\.google\.com|wixsite\.com|weebly\.com|blogspot\.com|wordpress\.com|carrd\.co|linktr\.ee|godaddysites\.com|square\.site|webflow\.io|netlify\.app|vercel\.app|github\.io|notion\.site|business\.site|facebook\.com|instagram\.com|linkedin\.com)$/i;

// Words that make a page read like a hiring channel rather than a business.
const HIRING_NAME = /\b(careers?|hiring|recruit(?:ment|ing|ers?)?|jobs?|talent|vacanc(?:y|ies)|hr)\b/i;
const STAFFING = /staffing|recruit|human resources/i;

const DAY = 86_400_000;

export function scoreCompany(c: CompanyFacts, now = Date.now()): Score {
  const signals: Signal[] = [];
  const missing: string[] = [];
  const add = signalAdder(signals);
  const name = c.name ?? c.slug;

  // Claimed size with no people behind it is the strongest tell a page has.
  const claimedMin = c.claimedSize?.min ?? null;
  const emp = c.employeesOnLinkedIn;
  if (claimedMin != null && emp != null) {
    if (claimedMin >= 200 && emp < Math.max(5, claimedMin * 0.02)) {
      add('company.size-mismatch', `Claims ${c.claimedSize!.label} but only ${emp} people list it on LinkedIn`, 25, 'discrepancy');
    } else if (claimedMin >= 51 && emp < 3) {
      add('company.size-mismatch', `Claims ${c.claimedSize!.label} but only ${emp} people list it on LinkedIn`, 15, 'discrepancy');
    }
  }
  if (emp == null) missing.push('Employees on LinkedIn');
  else if (emp === 0) add('company.no-employees', 'Nobody lists this company on their profile', 12);
  else if (emp < 5) add('company.few-employees', `Only ${emp} people list this company on their profile`, 6);
  else if (emp >= 50) add('company.employees', `${emp.toLocaleString('en-US')} people list this company on LinkedIn`, -10);

  // A business name that reads like a hiring channel, outside staffing firms.
  if (HIRING_NAME.test(name) && !STAFFING.test(c.industry ?? '')) {
    add('company.hiring-name', 'Name reads like a hiring page, a pattern used to impersonate real employers', 12, 'discrepancy');
  }

  // Website.
  const domain = siteDomain(c.website);
  if (!c.website) add('company.no-website', 'No website listed', 10);
  else if (domain && FREE_HOSTS.test(domain)) add('company.free-website', `Website is on a free host (${domain})`, 10);

  // Audience and activity.
  if (c.followers == null) missing.push('Follower count');
  else if (c.followers < 50) add('company.few-followers', `Only ${c.followers} followers`, 10);
  else if (c.followers < 300) add('company.low-followers', `Low follower count (${c.followers})`, 4);
  else if (c.followers >= 10_000) add('company.followers', `${c.followers.toLocaleString('en-US')} followers`, -6);
  if (c.posts.count === 0) add('company.no-posts', 'No recent public posts', 5);
  else if (c.posts.newestAt && now - c.posts.newestAt < 90 * DAY) add('company.active', 'Posted in the last 3 months', -4);

  // Page completeness.
  if (!c.logo.present) add('company.no-logo', 'No logo', 8);
  else if (c.logo.uploadedAt && now - c.logo.uploadedAt < 90 * DAY && c.foundedYear && new Date(now).getUTCFullYear() - c.foundedYear >= 5) {
    add('company.new-logo', `Logo added recently for a company founded in ${c.foundedYear}`, 5);
  }
  if (!c.industry) add('company.no-industry', 'No industry listed', 3);
  if (!c.foundedYear) missing.push('Founding year');
  if (!c.claimedSize) missing.push('Company size');
  if (c.type && /self-employed/i.test(c.type) && claimedMin != null && claimedMin > 10) {
    add('company.self-employed-large', `Listed as self-employed but claims ${c.claimedSize!.label}`, 10, 'discrepancy');
  }

  // Logged-in extras.
  const x = c.extras;
  if (!x) {
    missing.push('Employee sample and page ownership (needs signed-in LinkedIn)');
  } else {
    if (x.autoGenerated || x.claimable) add('company.unmanaged', 'Nobody manages this page (created automatically or unclaimed)', 6);
    if (x.paid) add('company.paid', 'Pays LinkedIn for services', -4);
    const e = x.employees;
    const visible = e ? e.sampled - e.hidden : 0;
    if (!e) {
      missing.push("Employee account ages (the employee search couldn't be read)");
    } else if (visible < 5) {
      missing.push('Employee account ages (too few visible employees)');
    } else {
      const share = e.newAccounts / visible;
      const label = `${e.newAccounts} of ${visible} sampled employees joined LinkedIn in the past year`;
      if (share >= 0.5) add('company.new-employees', label, 20, 'discrepancy');
      else if (share >= 0.3) add('company.new-employees', label, 8);
      else if (e.oldAccounts / visible >= 0.6) add('company.established-employees', `${e.oldAccounts} of ${visible} sampled employees have accounts older than 5 years`, -6);
    }
  }

  return finishScore(signals, missing);
}
