import { describe, expect, test } from 'bun:test';
import { profileIdFor } from './fixtures';
import { parseCompanyRecord, parseJobRecord, parsePeopleSearch, pageShowsVerifiedJob, type CompanyExtras, type JobExtras } from '../src/index';
import { parseMutual } from '../src/index';
import { scoreCompany, type CompanyFacts } from '../src/index';
import { scoreJob, type JobFacts } from '../src/index';

const NOW = Date.UTC(2026, 10, 18);
const DAY = 86_400_000;

describe('logged-in parsers', () => {
  test('job record', () => {
    const x = parseJobRecord({
      data: {
        applyMethod: { $type: 'com.linkedin.voyager.jobs.OffsiteApply', companyApplyUrl: 'https://jobs.example.com/apply/1' },
        listedAt: NOW - 2 * DAY,
        originalListedAt: NOW - 90 * DAY,
        expireAt: NOW + 28 * DAY,
        jobState: 'LISTED',
        workRemoteAllowed: true,
        thirdPartySourced: false,
      },
      included: [{ $type: 'com.linkedin.voyager.identity.shared.MiniProfile', publicIdentifier: 'sam-hiring', firstName: 'Sam', lastName: 'Lee' }],
    });
    expect(x).toEqual({
      applyUrl: 'https://jobs.example.com/apply/1',
      listedAt: NOW - 2 * DAY,
      originalListedAt: NOW - 90 * DAY,
      expireAt: NOW + 28 * DAY,
      state: 'LISTED',
      remote: true,
      thirdPartySourced: false,
      hiringTeam: [{ slug: 'sam-hiring', name: 'Sam Lee' }],
    });
    expect(pageShowsVerifiedJob('<span role="img" aria-label="Verified job">')).toBe(true);
    expect(pageShowsVerifiedJob('<span>Get verified</span>')).toBe(false);
  });

  test('company record', () => {
    const json = {
      included: [
        { $type: 'com.linkedin.voyager.organization.Company', universalName: 'other', autoGenerated: true },
        {
          $type: 'com.linkedin.voyager.organization.Company',
          universalName: 'example-co',
          entityUrn: 'urn:li:fs_normalized_company:4242',
          autoGenerated: false,
          claimable: false,
          paidCompany: true,
          staffingCompany: false,
          phone: { number: ' 555-0100' },
          confirmedLocations: [{}, {}],
        },
      ],
    };
    expect(parseCompanyRecord(json, 'example-co')).toEqual({
      companyId: 4242, autoGenerated: false, claimable: false, paid: true, staffing: false, phone: '555-0100', locations: 2,
    });
  });

  test('employee search keeps only counts', () => {
    const result = (memberId: number | null) => ({
      $type: 'com.linkedin.voyager.dash.search.EntityResultViewModel',
      trackingUrn: memberId ? `urn:li:member:${memberId}` : 'urn:li:member:headless',
      entityUrn: memberId ? `urn:li:fsd_entityResultViewModel:(urn:li:fsd_profile:${profileIdFor(memberId)},SEARCH_SRP,DEFAULT)` : 'x',
    });
    const s = parsePeopleSearch(
      {
        data: { data: { searchDashClustersByAll: { paging: { count: 12, start: 0, total: 40 } } } },
        included: [result(1_810_000_000), result(1_809_000_000), result(100_000_000), result(null)],
      },
      NOW,
    );
    expect(s).toEqual({ total: 40, sampled: 4, hidden: 1, newAccounts: 2, oldAccounts: 1 });
  });

  test('mutual connections text', () => {
    expect(parseMutual('Lara and David are mutual connections')).toBe(2);
    expect(parseMutual('Sam, Lee, and 12 other mutual connections')).toBe(14);
    expect(parseMutual('Alex is a mutual connection')).toBe(1);
    expect(parseMutual(null)).toBeNull();
    expect(parseMutual('are mutual connections')).toBeNull();
  });
});

const company = (extras: CompanyExtras | null, o: Partial<CompanyFacts> = {}): CompanyFacts => ({
  companyId: 4242, slug: 'example-co', name: 'Example Co', tagline: null, industry: 'Software Development', headquarters: null,
  type: 'Privately Held', foundedYear: 2010, claimedSize: { min: 51, max: 200, label: '51-200 employees' }, employeesOnLinkedIn: 80,
  followers: 2000, website: 'https://www.example.com', specialties: [], logo: { present: true, uploadedAt: null, url: null },
  posts: { count: 3, newestAt: NOW - 5 * DAY }, extras, ...o,
});
const extrasCo = (newAccounts: number, oldAccounts: number, o: Partial<CompanyExtras> = {}): CompanyExtras => ({
  autoGenerated: false, claimable: false, paid: false, staffing: false, phone: null, locations: 1,
  employees: { total: 80, sampled: 12, hidden: 0, newAccounts, oldAccounts }, ...o,
});
const job = (extras: JobExtras | null): JobFacts => ({
  jobId: '1', title: 'Support Specialist', company: { name: 'Example Co', slug: 'example-co' }, location: 'Remote', postedText: '1 day ago',
  postedAt: NOW - DAY, reposted: false, applicants: null, seniority: 'Mid-Senior level', employmentType: 'Full-time', jobFunction: null,
  industries: null, salary: { text: '$60,000/yr - $70,000/yr', min: 60000, max: 70000, period: 'year' }, apply: 'offsite',
  description: 'A normal job description with responsibilities, requirements and benefits. '.repeat(10),
  contacts: { emails: [], phones: [], urls: [] }, extras,
});
const extrasJob = (o: Partial<JobExtras> = {}): JobExtras => ({
  applyUrl: 'https://www.example.com/careers/1', listedAt: NOW - DAY, originalListedAt: NOW - DAY, expireAt: null, state: 'LISTED',
  remote: true, thirdPartySourced: false, verified: false, hiringTeam: [], ...o,
});

describe('logged-in signals', () => {
  test('companies whose sampled employees are mostly new accounts', () => {
    const ids = (c: CompanyFacts) => scoreCompany(c, NOW).signals.map((x) => x.id);
    expect(scoreCompany(company(extrasCo(8, 1)), NOW).signals.find((x) => x.id === 'company.new-employees')?.kind).toBe('discrepancy');
    expect(ids(company(extrasCo(1, 9)))).toContain('company.established-employees');
    expect(ids(company(extrasCo(1, 2, { autoGenerated: true })))).toContain('company.unmanaged');
    expect(scoreCompany(company(null), NOW).missing.join()).toContain('sign in');
  });

  test('apply links: company site and ATS are fine, other domains and forms are not', () => {
    const co = company(extrasCo(1, 9));
    const cs = scoreCompany(co, NOW);
    const ids = (x: JobExtras) => scoreJob(job(x), co, cs).signals.map((s) => s.id);
    expect(ids(extrasJob())).not.toContain('job.apply-domain');
    expect(ids(extrasJob({ applyUrl: 'https://boards.greenhouse.io/exampleco/jobs/1' }))).not.toContain('job.apply-domain');
    expect(ids(extrasJob({ applyUrl: 'https://example-co-careers.net/apply' }))).toContain('job.apply-domain');
    expect(ids(extrasJob({ applyUrl: 'https://forms.gle/abc' }))).toContain('job.apply-form');
    expect(ids(extrasJob({ verified: true }))).toContain('job.verified');
    expect(ids(extrasJob({ originalListedAt: NOW - 120 * DAY }))).toContain('job.reposted');
  });
});
