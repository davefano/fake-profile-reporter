import { describe, expect, test } from 'bun:test';
import { createSession, getCompany, getJob, type CompanyExtras, type JobExtras } from '../src/linkedin';
import { companyHtml, jobHtml } from './pages';

// A fake LinkedIn: public pages by path; signed-in reads go through the getters' functions.
function session(pages: Record<string, string>) {
  return createSession({
    fetch: async (url) => (pages[url] != null ? new Response(pages[url]) : new Response('nope', { status: 404 })),
  });
}

const companyExtras = (o: Partial<CompanyExtras> = {}): CompanyExtras => ({
  autoGenerated: false, claimable: false, paid: true, staffing: false, phone: null, locations: 1, employees: null, errors: {}, ...o,
});
const jobExtras = (o: Partial<JobExtras> = {}): JobExtras => ({
  applyUrl: null, listedAt: 1, originalListedAt: 1, expireAt: null, state: 'LISTED', remote: false, thirdPartySourced: false,
  verified: true, hiringTeam: [], errors: {}, ...o,
});

describe('getCompany', () => {
  const pages = { '/company/example-co/': companyHtml({}) };

  test('logged out: public facts, no extras', async () => {
    const r = await getCompany('example-co', { session: session(pages) });
    expect(r.facts.name).toBe('Example Co');
    expect(r.facts.extras).toBeUndefined();
    expect(r.errors).toEqual({});
  });

  test('a custom signed-in reader adds extras and its partial errors', async () => {
    const r = await getCompany('example-co', {
      session: session(pages),
      signedIn: async () => companyExtras({ errors: { employees: 'HTTP 400' } }),
    });
    expect(r.facts.extras?.paid).toBe(true);
    expect(r.errors).toEqual({ 'extras.employees': 'HTTP 400' });
  });

  test('a failed signed-in read keeps the public facts', async () => {
    const r = await getCompany('example-co', { session: session(pages), signedIn: async () => Promise.reject(new Error('HTTP 403')) });
    expect(r.facts.name).toBe('Example Co');
    expect(r.facts.extras).toBeNull();
    expect(r.errors).toEqual({ extras: 'HTTP 403' });
  });

  test('a missing page throws', async () => {
    await expect(getCompany('nobody', { session: session(pages) })).rejects.toThrow();
  });
});

describe('getJob', () => {
  const pages = { '/jobs-guest/jobs/api/jobPosting/4400000001': jobHtml({}), '/company/example-co/': companyHtml({}) };

  test('posting plus its company, with extras for both', async () => {
    const r = await getJob('4400000001', {
      session: session(pages),
      signedIn: { job: async () => jobExtras(), company: async () => companyExtras() },
    });
    expect(r.job.title).toBe('Customer Support Specialist');
    expect(r.job.extras?.verified).toBe(true);
    expect(r.company?.extras?.paid).toBe(true);
    expect(r.errors).toEqual({});
  });

  test('a missing company page and failed extras are recorded, the posting kept', async () => {
    const r = await getJob('4400000001', {
      session: session({ '/jobs-guest/jobs/api/jobPosting/4400000001': jobHtml({}) }),
      signedIn: { job: async () => jobExtras({ verified: null, errors: { verified: 'HTTP 403' } }), company: async () => companyExtras() },
    });
    expect(r.job.title).toBe('Customer Support Specialist');
    expect(r.company).toBeNull();
    expect(Object.keys(r.errors).sort()).toEqual(['company', 'extras.verified']);
  });
});
